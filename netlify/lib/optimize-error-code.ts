const publicCodes = new Set([
  'AI_CONTRACT_EMPTY_RESULT', 'AI_CONTRACT_ERROR', 'AI_CONTRACT_JSON_PARSE_FAILED',
  'AI_CONTRACT_NON_TEXT_RESPONSE', 'AI_CONTRACT_VALIDATION_FAILED', 'AI_RESPONSE_TRUNCATED',
  'AI_TIMEOUT', 'CONSUME_CREDITS_RPC_FAILED', 'OPTIMIZE_BILLING_RECONCILIATION',
  'OPTIMIZE_DEBIT_DECLINED', 'OPTIMIZE_FAILED', 'OPTIMIZE_NO_VERIFIED_EDITS',
  'OPTIMIZE_RESULT_RECOVERED', 'OPTIMIZE_TIMEOUT', 'OPTIMIZE_WORKER_FAILED',
]);

export function publicOptimizeCode(value: unknown, timeout = false): string {
  if (typeof value === 'string' && publicCodes.has(value)) return value;
  return timeout ? 'OPTIMIZE_TIMEOUT' : 'OPTIMIZE_FAILED';
}
